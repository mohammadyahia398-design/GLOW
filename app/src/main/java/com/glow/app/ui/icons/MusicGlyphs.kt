 * الأشكال مستخرجة من الصورة المرجعية مباشرة (نفس الزوايا والانحناءات والالتقاءات)
 * ومرسومة بدرجتين فقط: جسم خافت وتفصيل قوي. في نمط Duotone يُستعمل اللون
 * الثانوي، وفي النمطين الآخرين يصير الخافت بنسبة 40% من اللون الأساسي كما في المرجع.
 *
 * الاستعمال:
 *     GlowGlyph(MusicGlyphs.Note, tint = color, size = 24.dp)
 */

private const val SoftAlphaRef = 0.4f

private fun parse(s: String): FloatArray {
    val parts = s.split(' ')
    return FloatArray(parts.size) { parts[it].toFloat() }
}

private fun GlyphCanvas.traced(vararg shapes: FloatArray): Path = path {
    for (c in shapes) {
        if (c.size < 6) continue
        moveTo(c[0], c[1])
        var i = 2
        while (i + 1 < c.size) {
            lineTo(c[i], c[i + 1])
            i += 2
        }
        close()
    }
}

private fun GlyphCanvas.softFill(p: Path) {
    fill(p, Tone.Soft, if (spec.style == IconStyle.Duotone) 1f else SoftAlphaRef)
}

